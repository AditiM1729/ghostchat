import { network, artifacts } from 'hardhat';
import { mkdir, writeFile, rename } from 'node:fs/promises';
import type { Hex } from 'viem';
import { MST_CHAIN_ID, MST_EXPLORER } from '../../shared/network.js';
const { viem } = await network.create();
const client = await viem.getPublicClient();
if (await client.getChainId() !== MST_CHAIN_ID) throw new Error('Deployment is restricted to MST Testnet.');
const [wallet] = await viem.getWalletClients();
if (!wallet) throw new Error('No deployer configured. Use the MetaMask setup page at http://localhost:5173/setup, or set MST_PRIVATE_KEY only in your deployment shell.');
const artifact = await artifacts.readArtifact('GhostPayEscrow');
const hash = await wallet.deployContract({ abi: artifact.abi, bytecode: artifact.bytecode as Hex });
console.log(`Deployment submitted: ${MST_EXPLORER}/tx/${hash}`);
const receipt = await client.waitForTransactionReceipt({ hash, confirmations: 2, timeout: 240000 });
if (receipt.status !== 'success' || !receipt.contractAddress) throw new Error('Deployment failed.');
const deployment = { address: receipt.contractAddress, chainId: MST_CHAIN_ID, blockNumber: String(receipt.blockNumber), configured: true, transactionHash: receipt.transactionHash };
await mkdir('../deployments', { recursive: true });
await writeFile('../deployments/mst-testnet.json.tmp', JSON.stringify(deployment, null, 2));
await rename('../deployments/mst-testnet.json.tmp', '../deployments/mst-testnet.json');
console.log(`GhostPayEscrow deployed: ${MST_EXPLORER}/address/${deployment.address}`);
console.log('Restart the relay, or use Verify & register contract on the setup page with this transaction hash.');
